SUMMARY_PROMPT = """
你是一名中文视频内容整理助手。请基于提供的完整音频或完整转写文本，输出高质量 Markdown 视频笔记。

要求：
1. 先写「一句话总结」，说明视频最核心的主题和结论。
2. 写「核心内容」，按视频实际逻辑整理 5-10 个要点；不要机械凑数。
3. 对重要概念、论据、步骤、数据、例子进行解释，保留真正有信息量的内容。
4. 写「值得记住的结论」，提炼 3-6 条最有价值的信息。
5. 如果视频包含教程或操作流程，再增加「操作步骤」；如果没有就不要生成这一节。
6. 过滤片头片尾、关注点赞、重复口头禅、无意义寒暄和广告式废话。
7. 不要编造输入中没有的信息。听不清或无法确认的内容应明确说明。
8. 输出中文 Markdown，不要写“作为 AI”等无关说明。
""".strip()

TRANSCRIPTION_PROMPT = """
请完整、忠实地转写这段音频中的可辨识语音。要求：
1. 尽量保留原始语义、数字、专有名词和步骤顺序。
2. 删除明显的无意义重复口头禅，但不要总结或改写内容。
3. 不确定的词语用【听不清】标记，不要凭空补全。
4. 只输出转写正文，不要输出解释、摘要或 Markdown 标题。
""".strip()


def transcript_summary_input(transcript: str) -> str:
    return f"{SUMMARY_PROMPT}\n\n以下是视频音频的完整转写文本：\n\n{transcript.strip()}"
